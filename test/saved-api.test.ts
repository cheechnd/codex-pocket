import { test } from 'node:test';
import assert from 'node:assert/strict';
import { AccessControl } from '../src/server/access.js';
import { createApp } from '../src/server/app.js';
import { mockDaemon } from './mock.js';
import { Transport } from '../src/daemon/transport.js';
import { DaemonAdapter } from '../src/daemon/adapter.js';

test('saved browsing is authenticated/read-only; opening is explicit CSRF-protected and cannot override configuration', async t => {
  const mock = await mockDaemon(), adapter = new DaemonAdapter(new Transport(mock.socket)); await adapter.transport.connect();
  const access = new AccessControl(`${mock.directory}/access`);
  const app = createApp(adapter, 44323, { access }); await new Promise<void>(resolve => app.server.listen(44323, '127.0.0.1', resolve));
  t.after(async () => { await app.close(); await mock.close(); });
  mock.saved([{ id: 'saved-old', name: 'Older conversation', preview: 'Synthetic saved history', cwd: '/scratch', status: { type: 'notLoaded' }, updatedAt: 1, recencyAt: 1 }]);
  const get = (path: string, cookie?: string, origin?: string) => fetch(app.origin + path, { headers: { ...(cookie ? { Cookie: cookie } : {}), ...(origin ? { Origin: origin } : {}) } });
  const headers = { Origin: app.origin, 'Content-Type': 'application/json', 'X-Pocket-Request': '1' };
  const paired = await fetch(app.origin + '/api/pair', { method: 'POST', headers, body: JSON.stringify({ code: access.pairingCode() }) });
  const Cookie = paired.headers.get('set-cookie')!.split(';')[0];
  const post = (body = {}, otherHeaders = headers) => fetch(app.origin + '/api/threads/saved-old/open', { method: 'POST', headers: { ...otherHeaders, Cookie }, body: JSON.stringify(body) });
  assert.equal((await get('/api/saved-threads')).status, 401);
  assert.equal((await get('/api/saved-threads', Cookie, 'https://evil.example')).status, 403);
  const listed = await get('/api/saved-threads?search=Older', Cookie); assert.equal(listed.status, 200);
  const page = await listed.json() as any; assert.equal(page.data[0].id, 'saved-old'); assert.equal(page.data[0].loaded, false);
  assert.equal(mock.calls.some(call => call.method === 'thread/resume'), false);
  assert.equal((await get('/api/threads/saved-old/history', Cookie)).status, 404);
  assert.equal((await get('/api/threads/saved-old/open', Cookie)).status, 404);
  assert.equal((await post({}, { ...headers, Origin: 'https://evil.example' })).status, 403);
  assert.equal((await post({}, { 'Content-Type': 'application/json' } as any)).status, 403);
  assert.equal((await post({ sandbox: 'danger-full-access' })).status, 400);
  assert.equal((await post({ path: '/anywhere' })).status, 400);
  assert.equal((await get(`/api/saved-threads?search=${'a'.repeat(201)}`, Cookie)).status, 400);
  assert.equal((await get(`/api/saved-threads?cursor=${'a'.repeat(4097)}`, Cookie)).status, 400);
  assert.equal(mock.calls.some(call => call.method === 'thread/resume'), false);
  const opened = await post(); assert.equal(opened.status, 200); const thread = await opened.json() as any;
  assert.equal(thread.id, 'saved-old'); assert.equal(thread.loaded, true);
  assert.deepEqual(mock.calls.filter(call => call.method === 'thread/resume').map(call => call.params), [{ threadId: 'saved-old', excludeTurns: true }]);
  assert.equal((await get('/api/threads/saved-old/history', Cookie)).status, 200);
  assert.equal(mock.calls.some(call => /turn\/start|thread\/start|thread\/fork|thread\/archive|thread\/unarchive/.test(call.method)), false);
});
